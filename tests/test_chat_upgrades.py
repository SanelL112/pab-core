@pytest.mark.asyncio
async def test_smart_auto_routes_code_to_qwen_coder():
    async def _inline_to_thread(func, /, *args, **kwargs):
        return func(*args, **kwargs)

    with patch("bot.ai_bridge.load_state", return_value={"user_models": {"123": "auto"}}), \
         patch("bot.ai_bridge.detect_topic", return_value="programming"), \
         patch("bot.ai_bridge.check_pii", return_value=(True, "code", [])), \
         patch(
             "bot.ai_bridge.call_agy_result",
             return_value=InferenceResult.success("def solve(): pass", provider="agy", model="Gemini 3.7 Flash (Low)"),
         ) as mock_agy, \
         patch("bot.ai_bridge.asyncio.to_thread", new=_inline_to_thread):

        resp = await send_to_antigravity_and_wait(
            "Write a python script to parse CSV files",
            chat_id=123,
            cloud_consent=True,
        )
        assert "def solve(): pass" in resp
        assert "Google" in resp
        assert mock_agy.call_args.kwargs["model"] == "flash"


