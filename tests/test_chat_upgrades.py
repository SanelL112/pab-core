def test_session_history_lifecycle(tmp_path, monkeypatch):
    monkeypatch.setattr(bot.ai_bridge, "CHAT_HISTORY_DIR", tmp_path)

    chat_id = 99999
    turns = get_session_turns(chat_id)
    assert turns == []

    append_session_turn(chat_id, "What is Newton's second law?", "F = ma\n\n_(Generated by: local)_")
    turns = get_session_turns(chat_id)
    assert len(turns) == 1
    assert turns[0]["user"] == "What is Newton's second law?"
    assert turns[0]["assistant"] == "F = ma"  # Generation badge stripped for clean memory

    append_session_turn(chat_id, "Can you give an example?", "Pushing a cart.")
    turns = get_session_turns(chat_id)
    assert len(turns) == 2

    assert clear_session(chat_id) is True
    turns = get_session_turns(chat_id)
    assert turns == []


